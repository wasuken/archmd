package main

import (
	"flag"
	"fmt"
	"io"
	"os"
)

const version = "0.2.0"
const usage = "usage: archmd [--dir path] <init|prompt|remove|check|build|split|template|notices|version|help> [options]\n"
const agentExamples = "  archmd prompt | <agent> && archmd check\n" +
	"  archmd prompt | claude -p && archmd check\n" +
	"  archmd prompt | codex exec - && archmd check\n" +
	"  書き込み権限のフラグは各エージェントのドキュメントを確認してください。\n"
const nextGuidance = "Next: ARCHITECTURE.md is a skeleton. Have your coding agent fill it in:\n" +
	"  archmd prompt | <your-agent> && archmd check\n" +
	"  (agent examples: claude -p / codex exec -). Check the agent's docs for the flags that let it write files.\n"

const writeAgentsHelp = "  init --write-agents: 既存の AGENTS.md / CLAUDE.md にブロックを追記する。既にあれば何もしない\n"

func writeHelp(out io.Writer) error {
	path, found, err := commonRulesLocation()
	if err != nil {
		return err
	}
	status := "not found"
	if found {
		status = "found"
	}
	_, err = fmt.Fprintf(out, "%s\nConfiguration:\n  common.md: %s\n  Shared rules for all projects, such as document language; included in the block generated by init and in prompt output.\n  status: %s\n\nExamples:\n%s", usage, path, status, agentExamples)
	if err != nil {
		return err
	}
	_, err = io.WriteString(out, "\nInit:\n"+writeAgentsHelp)
	return err
}

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

func run(args []string, out, errOut io.Writer) int {
	global := flag.NewFlagSet("archmd", flag.ContinueOnError)
	global.SetOutput(errOut)
	global.Usage = func() {}
	dir := global.String("dir", ".", "target directory")
	if err := global.Parse(args); err != nil {
		if err == flag.ErrHelp {
			if err := writeHelp(out); err != nil {
				fmt.Fprintln(errOut, err)
				return 1
			}
			return 0
		}
		return 2
	}
	args = global.Args()
	if len(args) == 0 {
		fmt.Fprint(errOut, usage)
		return 2
	}
	command := args[0]
	switch command {
	case "init", "prompt", "remove", "check", "build", "split", "template", "notices", "version", "help":
	default:
		fmt.Fprint(errOut, usage)
		return 2
	}
	fs := flag.NewFlagSet(command, flag.ContinueOnError)
	fs.SetOutput(errOut)
	fs.StringVar(dir, "dir", *dir, "target directory")
	maxLines, sectionLines := 0, 80
	yes, keepArchitecture := false, false
	writeAgents := false
	if command == "init" {
		fs.BoolVar(&writeAgents, "write-agents", false, "既存の AGENTS.md / CLAUDE.md にブロックを追記する。既にあれば何もしない")
		fs.Usage = func() { fmt.Fprint(errOut, writeAgentsHelp) }
	}
	if command == "remove" {
		fs.BoolVar(&yes, "yes", false, "apply removal (default: dry-run)")
		fs.BoolVar(&keepArchitecture, "keep-architecture-md", false, "keep ARCHITECTURE.md and remove its generated header")
	}
	if command == "init" || command == "prompt" || command == "check" {
		fs.IntVar(&maxLines, "max-lines", 0, "maximum total lines")
	}
	if command == "check" {
		fs.IntVar(&sectionLines, "max-section-lines", 80, "maximum section lines")
	}
	if err := fs.Parse(args[1:]); err != nil {
		if err == flag.ErrHelp {
			return 0
		}
		return 2
	}
	invalid := fs.NArg() != 0
	fs.Visit(func(f *flag.Flag) {
		if f.Name == "max-lines" && maxLines <= 0 || f.Name == "max-section-lines" && sectionLines <= 0 {
			invalid = true
		}
	})
	if invalid {
		fmt.Fprintln(errOut, "invalid arguments: line limits must be positive integers; positional arguments are not accepted")
		return 2
	}
	var err error
	switch command {
	case "init":
		err = initProject(*dir, maxLines, writeAgents, out, errOut)
	case "prompt":
		err = promptProject(*dir, maxLines, out)
	case "remove":
		err = removeProject(*dir, yes, keepArchitecture, out)
	case "check":
		return checkProject(*dir, maxLines, sectionLines, out)
	case "build":
		err = buildProject(*dir)
	case "split":
		err = splitProject(*dir)
	case "template":
		_, err = io.WriteString(out, architectureTemplate)
	case "notices":
		_, err = io.WriteString(out, thirdPartyNotices)
	case "version":
		_, err = fmt.Fprintln(out, version)
	case "help":
		err = writeHelp(out)
	}
	if err != nil {
		fmt.Fprintln(errOut, err)
		return 1
	}
	return 0
}
