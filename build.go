package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedHeader = "<!-- GENERATED by archmd build. DO NOT EDIT. Edit files in .architecture/ and run `archmd build`. -->"

func buildContent(dir string) ([]byte, error) {
	source := filepath.Join(dir, ".architecture")
	entries, err := os.ReadDir(source)
	if err != nil {
		return nil, err
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
	parts := []string{generatedHeader}
	for _, entry := range entries {
		if filepath.Ext(entry.Name()) != ".md" || !entry.Type().IsRegular() {
			continue
		}
		data, err := os.ReadFile(filepath.Join(source, entry.Name()))
		if err != nil {
			return nil, err
		}
		parts = append(parts, strings.TrimRight(normalize(string(data)), "\n"))
	}
	return []byte(strings.Join(parts, "\n\n") + "\n"), nil
}
func buildProject(dir string) error {
	content, err := buildContent(dir)
	if err != nil {
		return fmt.Errorf("build: %w", err)
	}
	return os.WriteFile(filepath.Join(dir, "ARCHITECTURE.md"), content, 0644)
}
